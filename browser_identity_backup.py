
"""
Patente B - Automatic anonymous student identity.

JavaScript:
    Reads or creates a persistent browser UUID.

PostgreSQL:
    Registers that same UUID without generating
    replacement student identities.

No login forms or registration buttons required.
"""

import json
import logging
import uuid
from pathlib import Path

import streamlit as st
import streamlit.components.v1 as components

from student_tracking import register_browser_student


# =========================================
# CONFIGURATION
# =========================================

BROWSER_ID_KEY = "patenteb_browser_id"

COMPONENT_DIR = (
    Path(__file__).resolve().parent
    / "identity_component"
)

identity_component = components.declare_component(
    "patenteb_browser_identity",
    path=str(COMPONENT_DIR),
)


# =========================================
# VALIDATE STUDENT ID
# =========================================

def validate_browser_id(value):
    """Extract a valid UUID from browser storage."""

    if isinstance(value, dict):
        value = value.get(BROWSER_ID_KEY)

    if isinstance(value, str):
        try:
            decoded = json.loads(value)

            if isinstance(decoded, dict):
                value = decoded.get(BROWSER_ID_KEY)

            elif isinstance(decoded, str):
                value = decoded

        except (ValueError, TypeError):
            pass

    try:
        return str(uuid.UUID(str(value)))

    except (ValueError, TypeError, AttributeError):
        return None


# =========================================
# GET CONFIRMED STUDENT ID
# =========================================

def get_browser_id():
    """
    Return the confirmed student identity.

    Never return an unregistered browser ID.
    """

    if not st.session_state.get("identity_resolved"):
        return None

    return validate_browser_id(
        st.session_state.get("browser_id")
    )


# =========================================
# INITIALIZE BROWSER IDENTITY
# =========================================

def initialize_browser_identity():
    """
    Automatically recover or register a student.

    The browser creates or retrieves the UUID.
    PostgreSQL registers the same UUID.

    No replacement UUID is generated by Python.
    """

    try:
        # Always read the current browser identity.
        # Do not trust a previous session-state ID
        # before the component confirms storage.

        result = identity_component(
            key="patenteb_browser_identity_component",
            default=None,
        )

        if not isinstance(result, dict):
            return None

        if result.get("ready") is not True:
            return None

        browser_id = validate_browser_id(
            result.get("browser_id")
        )

        if not browser_id:
            logging.error(
                "Browser identity component returned "
                "an invalid student ID."
            )
            return None

        # Prevent unnecessary database writes
        # during Streamlit reruns.

        if (
            st.session_state.get("identity_resolved")
            and st.session_state.get("browser_id")
            == browser_id
        ):
            return browser_id

        # Register the browser UUID.
        # PostgreSQL reuses the record if it exists.

        registered_id = register_browser_student(
            browser_id
        )

        if registered_id != browser_id:
            logging.error(
                "Unable to confirm browser identity "
                "in PostgreSQL."
            )
            return None

        # Only mark identity resolved after
        # PostgreSQL confirms registration.

        st.session_state.browser_id = browser_id
        st.session_state.identity_resolved = True

        # Keep compatibility with existing code
        # that checks registered_student_id.

        st.session_state.registered_student_id = (
            browser_id
        )

        return browser_id

    except Exception:
        logging.exception(
            "Unable to initialize browser identity"
        )
        return None


# =========================================
# COMPATIBILITY FUNCTIONS
# =========================================

def create_browser_id():
    return initialize_browser_identity()


def ensure_session_browser_id():
    return get_browser_id()
